"""Keep independent legacy compilations from changing another terminal session."""
from contextlib import ExitStack
import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import app as web
import test_orchestrator as sessions


ROOT = Path(__file__).resolve().parents[1]
CALCULATOR = 'seq { print("CALCULATOR_SESSION"); }'
FIBONACCI = 'seq { var a = 0; var b = 1; print("FIBONACCI_RUN", a, b); }'


class LegacySessionIsolationTests(unittest.TestCase):
    def setUp(self):
        (ROOT / "output").mkdir(exist_ok=True)
        temporary = tempfile.TemporaryDirectory(dir=ROOT / "output", prefix="legacy-session-test-")
        self.addCleanup(temporary.cleanup)
        self.work = Path(temporary.name)
        self.examples = self.work / "examples"
        self.examples.mkdir()
        self.output = self.work / "output"
        self.session_file = self.work / "session.json"
        (self.examples / "calculator.minipar").write_text(CALCULATOR, encoding="utf-8")
        (self.examples / "fibonacci.minipar").write_text(FIBONACCI, encoding="utf-8")
        self.generation = 0
        patches = ExitStack()
        self.addCleanup(patches.close)
        patches.enter_context(patch.object(web, "TESTS_DIR", str(self.examples)))
        patches.enter_context(patch.object(web, "OUTPUT_DIR", str(self.output)))
        patches.enter_context(patch.object(web, "get_terminal_id", return_value="web-owner"))
        patches.enter_context(patch.object(sessions, "get_terminal_id", return_value="web-owner"))
        patches.enter_context(patch.object(sessions, "SESSION_FILE", str(self.session_file)))
        # Exercise the real completion/archive/cleanup lifecycle without its
        # deliberate two-second pause for terminal participants.
        patches.enter_context(patch.object(sessions.time, "sleep", return_value=None))
        self.client = web.app.test_client()

    def seed_session(self, *, filename="calculator.minipar", owner="web-owner", status="running"):
        self.generation += 1
        session = {
            "test_file": filename,
            "titulo": "Sessão que deve permanecer isolada",
            "initiator_terminal": owner,
            "created_at": f"2026-11-09T17:00:{self.generation:02d}.000000",
            "status": status,
            "phase": "ready",
            "phase_message": "Estado inicial reservado aos participantes",
            "progress_percent": 45,
            "progress_log": [{"time": "17:00:00", "message": "SESSION_SENTINEL", "source": "system"}],
            "execution_output": "ORIGINAL_SESSION_OUTPUT",
            "required_participants": 2,
            "participants": [{"terminal_id": owner, "role": "server"},
                             {"terminal_id": "participant", "role": "client"}],
        }
        # A different indentation from the production writer catches even a
        # needless rewrite whose decoded JSON happens to have equal values.
        self.session_file.write_bytes(json.dumps(session, ensure_ascii=False, indent=4).encode("utf-8"))
        return session, self.session_file.read_bytes()

    def compile_request(self, code=CALCULATOR, filename="calculator.minipar", *,
                        compiler_exit=0, runtime_exit=0, missing_executable=False,
                        compiler_timeout=False, runtime_timeout=False, runtime_error=False,
                        after_compilation=None):
        compiled_sources = []

        def fake_process(command, **kwargs):
            main_index = next((index for index, value in enumerate(command)
                               if Path(str(value)).name == "main.py"), None)
            if main_index is not None:
                source = Path(command[main_index + 1])
                compiled_sources.append(source.read_text(encoding="utf-8"))
                directory = Path(command[command.index("--output-dir") + 1])
                stem = command[main_index + 2]
                directory.mkdir(parents=True, exist_ok=True)
                if compiler_timeout:
                    if after_compilation:
                        after_compilation()
                    raise subprocess.TimeoutExpired(command, kwargs.get("timeout", 15))
                if compiler_exit == 0:
                    (directory / f"{stem}.cpp").write_text("// generated by the compiler fixture\n", encoding="utf-8")
                    (directory / f"{stem}.tac").write_text("print SESSION_FIXTURE\n", encoding="utf-8")
                    if not missing_executable:
                        Path(web.executable_path(str(directory), stem)).write_bytes(b"MZ-test-fixture")
                if after_compilation:
                    after_compilation()
                return subprocess.CompletedProcess(command, compiler_exit, "COMPILER_LOG\n",
                                                   "COMPILER_FAILURE\n" if compiler_exit else "")
            if runtime_timeout:
                raise subprocess.TimeoutExpired(command, kwargs.get("timeout", 30))
            if runtime_error:
                raise OSError("RUNTIME_COULD_NOT_START")
            return subprocess.CompletedProcess(command, runtime_exit, "CURRENT_PROGRAM_OUTPUT\n",
                                               "RUNTIME_FAILURE\n" if runtime_exit else "")

        with patch.object(web.subprocess, "run", side_effect=fake_process) as process:
            response = self.client.post("/api/compile", json={"code": code, "filename": filename, "inputs": []})
        self.assertEqual(compiled_sources, [code], "The request must compile its own current source")
        return response, process.call_count

    def assert_cancelled(self, created_at):
        current = sessions._load_session()
        self.assertIsNotNone(current)
        self.assertEqual(current["created_at"], created_at)
        self.assertEqual(current["status"], "cancelled")
        self.assertEqual(current["phase"], "cancelled")
        snapshot = self.client.get("/api/session", query_string={"created_at": created_at}).get_json()
        self.assertFalse(snapshot["active"], "A failed request left terminal participants waiting")

    def test_independent_fibonacci_keeps_active_calculator_session_byte_identical(self):
        for failure in ({}, {"compiler_exit": 2}, {"runtime_exit": 7}):
            with self.subTest(failure=failure):
                _, before = self.seed_session()
                response, _ = self.compile_request(FIBONACCI, "fibonacci.minipar", **failure)
                self.assertEqual(response.status_code, 200)
                self.assertEqual(self.session_file.read_bytes(), before,
                                 "Independent Fibonacci changed the calculator's progress, output or lifecycle")

    def test_same_filename_with_another_owner_or_edited_source_keeps_session_intact(self):
        cases = (("different-owner", "another-terminal", CALCULATOR),
                 ("edited-source", "web-owner", CALCULATOR + "\n# edited in the browser"))
        for case, owner, code in cases:
            for failure in ({}, {"compiler_exit": 2}, {"runtime_exit": 7}):
                with self.subTest(case=case, failure=failure):
                    _, before = self.seed_session(owner=owner)
                    response, _ = self.compile_request(code, **failure)
                    self.assertEqual(response.status_code, 200)
                    self.assertEqual(self.session_file.read_bytes(), before,
                                     "A matching filename alone must not grant ownership of a terminal session")

    def test_completed_and_cancelled_sessions_are_not_reopened(self):
        for status in ("completed", "cancelled"):
            with self.subTest(status=status):
                _, before = self.seed_session(status=status)
                response, _ = self.compile_request()
                self.assertTrue(response.get_json()["success"], response.get_json())
                self.assertEqual(self.session_file.read_bytes(), before)

    def test_own_success_completes_archives_and_finalizes_the_session(self):
        session, _ = self.seed_session()
        with patch.object(web, "finalize_test_execution", wraps=web.finalize_test_execution) as finalize:
            response, calls = self.compile_request()
        self.assertEqual(response.status_code, 200)
        self.assertTrue(response.get_json()["success"], response.get_json())
        self.assertEqual(calls, 2)
        finalize.assert_called_once()
        completed = sessions.load_completed_session(session["created_at"])
        self.assertIsNotNone(completed, "Successful completion was not available to late polling participants")
        self.assertEqual(completed["status"], "completed")
        self.assertEqual(completed["phase"], "done")
        self.assertEqual(completed["progress_percent"], 100)
        self.assertIn("CURRENT_PROGRAM_OUTPUT", completed["execution_output"])
        self.assertFalse(self.session_file.exists(), "Completion did not clear the active session")

    def test_own_failures_cancel_instead_of_finishing_or_staying_at_ninety_percent(self):
        failures = ({"compiler_exit": 2}, {"runtime_exit": 7}, {"compiler_timeout": True},
                    {"runtime_timeout": True}, {"runtime_error": True}, {"missing_executable": True})
        for failure in failures:
            with self.subTest(failure=failure):
                session, _ = self.seed_session()
                with patch.object(web, "finalize_test_execution", wraps=web.finalize_test_execution) as finalize:
                    response, _ = self.compile_request(**failure)
                self.assertIn(response.status_code, (200, 500))
                self.assertFalse(response.get_json()["success"], response.get_json())
                finalize.assert_not_called()
                self.assert_cancelled(session["created_at"])

    def test_replacement_created_during_compilation_is_untouched_then_owned_by_a_fresh_request(self):
        for failure in ({}, {"compiler_exit": 2}, {"runtime_exit": 7}):
            with self.subTest(failure=failure):
                original, _ = self.seed_session()
                replacement = {}

                def replace_session():
                    replacement["session"], replacement["bytes"] = self.seed_session()

                response, _ = self.compile_request(after_compilation=replace_session, **failure)
                self.assertEqual(response.get_json()["success"], not failure, response.get_json())
                self.assertNotEqual(replacement["session"]["created_at"], original["created_at"])
                self.assertEqual(self.session_file.read_bytes(), replacement["bytes"],
                                 "The first request wrote to or cancelled a newer session with the same owner and filename")
                self.assertIsNone(sessions.load_completed_session(replacement["session"]["created_at"]))

                # The next HTTP request must take its own snapshot rather than
                # retaining the previous request's created_at or rejecting the new one.
                response, _ = self.compile_request()
                self.assertTrue(response.get_json()["success"], response.get_json())
                completed = sessions.load_completed_session(replacement["session"]["created_at"])
                self.assertIsNotNone(completed)
                self.assertEqual(completed["status"], "completed")
                self.assertIn("CURRENT_PROGRAM_OUTPUT", completed["execution_output"])


if __name__ == "__main__":
    unittest.main()
